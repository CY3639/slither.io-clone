#!/usr/bin/env bash
# Generate submission/submission-infra.yml from the DEPLOYED resources. Every ARN is read back from
# AWS (CloudFormation outputs or describe calls); nothing is typed by hand or guessed.
# Format follows the A2 submission file (cloudInfrastructure list + metaData + studentDetail).
source "$(dirname "$0")/config.sh"
out="$REPO_ROOT/submission/submission-infra.yml"
mkdir -p "$(dirname "$out")"

q() { aws "$@" --output text; }
must() { [[ -n "$1" && "$1" != None ]] || die "could not resolve $2"; echo "$1"; }

cluster_arn=$(must "$(stack_output "$STACK_BACKEND" ClusterArn)" cluster)
service_arn=$(must "$(stack_output "$STACK_BACKEND" ServiceArn)" service)
taskdef_arn=$(must "$(q ecs describe-services --cluster "$PREFIX-cluster" --services "$PREFIX-game" --query 'services[0].taskDefinition')" taskdef)
scaling_target=$(must "$(q application-autoscaling describe-scalable-targets --service-namespace ecs --resource-ids "service/$PREFIX-cluster/$PREFIX-game" --query 'ScalableTargets[0].ScalableTargetARN')" scalable-target)
occ_policy=$(must "$(stack_output "$STACK_BACKEND" OccupancyPolicyArn)" occupancy-policy)
cpu_policy=$(must "$(stack_output "$STACK_BACKEND" CpuPolicyArn)" cpu-policy)
alb_arn=$(must "$(stack_output "$STACK_BACKEND" LoadBalancerArn)" alb)
game_tg=$(must "$(stack_output "$STACK_BACKEND" GameTargetGroupArn)" game-tg)
api_tg=$(must "$(stack_output "$STACK_BACKEND" ApiTargetGroupArn)" api-tg)
listener=$(must "$(q elbv2 describe-listeners --load-balancer-arn "$alb_arn" --query 'Listeners[0].ListenerArn')" listener)
repo_arn=$(must "$(stack_output "$STACK_DATA" RepositoryArn)" ecr)
table_arn=$(must "$(stack_output "$STACK_DATA" TableArn)" table)
queue_arn=$(must "$(stack_output "$STACK_DATA" QueueArn)" queue)
dlq_arn=$(must "$(stack_output "$STACK_DATA" DLQArn)" dlq)
secret_arn=$(must "$(stack_output "$STACK_DATA" SessionSecretArn)" secret)
worker_arn=$(must "$(q lambda get-function-configuration --function-name "$PREFIX-event-worker" --query FunctionArn)" worker)
api_arn=$(must "$(q lambda get-function-configuration --function-name "$PREFIX-leaderboard-api" --query FunctionArn)" api)
esm_arn=$(must "$(q lambda list-event-source-mappings --function-name "$PREFIX-event-worker" --query 'EventSourceMappings[0].EventSourceMappingArn')" esm)
dist_arn=$(must "$(stack_output "$STACK_FRONTEND" DistributionArn)" distribution)
dist_domain=$(must "$(stack_output "$STACK_FRONTEND" DistributionDomain)" distribution-domain)
param_arn=$(must "$(q ssm get-parameter --name "$ORIGIN_SECRET_PARAM" --query Parameter.ARN)" origin-param)
dashboard_arn=$(must "$(q cloudwatch get-dashboard --dashboard-name "$PREFIX" --query DashboardArn)" dashboard)
alarm_arns=$(q cloudwatch describe-alarms --alarm-name-prefix "$PREFIX-" --query 'MetricAlarms[].AlarmArn' | tr '\t' '\n')
log_game="arn:aws:logs:$AWS_REGION:$ACCOUNT_ID:log-group:$GAME_LOG_GROUP"
aws logs describe-log-groups --log-group-name-prefix "$GAME_LOG_GROUP" --query 'logGroups[0].arn' --output text | grep -q "$GAME_LOG_GROUP" || die "game log group missing"
stack_arn() { q cloudformation describe-stacks --stack-name "$1" --query 'Stacks[0].StackId'; }

entry() { printf '  - type: %s\n    arn: %s\n    description: %s\n\n' "$1" "$2" "$3"; }

{
cat <<EOF
# Generated by infra/scripts/generate-submission-yaml.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
# from the live account $ACCOUNT_ID ($AWS_REGION). Do not edit ARNs by hand; rerun the script.
cloudInfrastructure:
EOF
entry "CloudFront distribution" "$dist_arn" "Edge cache and single HTTPS/WSS entry point (https://$dist_domain). Serves the fingerprinted client from S3 (1-year immutable cache), proxies /ws to the ALB uncached and caches /api/leaderboard for 10 s."
entry "S3 bucket - frontend" "arn:aws:s3:::$FRONTEND_BUCKET" "Private object storage for the built Phaser client; readable only by the CloudFront distribution via Origin Access Control."
entry "S3 bucket - artifacts" "arn:aws:s3:::$ARTIFACTS_BUCKET" "Private bucket holding versioned Lambda deployment packages."
entry "Application Load Balancer" "$alb_arn" "Dispatcher-push load distribution of new WebSocket connections across ECS tasks; forwards only requests carrying the CloudFront secret header (others get 403)."
entry "ALB listener" "$listener" "Listener rules routing /ws, /health, /ready, /status to the game target group and /api/* to the leaderboard Lambda."
entry "ALB target group - game" "$game_tg" "IP target group of the Fargate game tasks, health-checked on /ready."
entry "ALB target group - API" "$api_tg" "Lambda target group for the leaderboard API."
entry "ECS cluster" "$cluster_arn" "Fargate cluster with Container Insights (running/desired task metrics)."
entry "ECS service" "$service_arn" "Game service: each task runs one authoritative world (up to 4 humans plus NPCs = 50 snakes); tasks in private subnets."
entry "ECS task definition" "$taskdef_arn" "0.25 vCPU / 0.5 GB ARM64 game container with health check, awslogs and environment-based configuration."
entry "Application Auto Scaling scalable target" "$scaling_target" "ECS Service Auto Scaling of the game service between 1 and 6 tasks."
entry "Application Auto Scaling policy - occupancy" "$occ_policy" "Target tracking on the custom WorldOccupancyPct metric (75 %): adds worlds before they are all full."
entry "Application Auto Scaling policy - CPU" "$cpu_policy" "Target tracking on ECS service CPU (50 %) as a safety net for CPU-bound simulation."
entry "ECR repository" "$repo_arn" "Versioned arm64 container images of the game server."
entry "SQS queue" "$queue_arn" "Durable asynchronous channel for game events (PLAYER_DIED, SESSION_ENDED, WORLD_STARTED, WORLD_COMPLETED)."
entry "SQS queue - DLQ" "$dlq_arn" "Dead-letter queue receiving events that failed processing 3 times."
entry "Lambda function - event worker" "$worker_arn" "Consumes SQS batches and applies events idempotently to DynamoDB (partial batch failures)."
entry "Lambda event source mapping" "$esm_arn" "SQS to Lambda trigger: batch 10, 2 s window, ReportBatchItemFailures, max concurrency 2."
entry "Lambda function - leaderboard API" "$api_arn" "Serves /api/leaderboard (GSI query) and /api/player behind the ALB; responses edge-cached."
entry "DynamoDB table" "$table_arn" "Single-table store for player profiles, death history, world records and idempotency markers; sparse GSI1 leaderboard."
entry "Secrets Manager secret" "$secret_arn" "HMAC key signing anonymous player IDs, read by game tasks at startup."
entry "SSM parameter" "$param_arn" "SecureString holding the CloudFront-to-ALB origin verification header value."
entry "CloudWatch dashboard" "$dashboard_arn" "Scaling, game loop, ALB, SQS/Lambda/DynamoDB and CloudFront metrics."
for a in $alarm_arns; do entry "CloudWatch alarm" "$a" "Operational alarm (see infra/cloudformation/monitoring.yml)."; done
entry "CloudWatch log group" "$log_game" "Structured JSON logs and EMF custom metrics from the game tasks."
for s in "$STACK_DATA" "$STACK_BACKEND" "$STACK_FRONTEND" "$STACK_MONITORING"; do
    entry "CloudFormation stack" "$(stack_arn "$s")" "Infrastructure as code stack $s."
done
cat <<EOF
metaData:
  qutUsernameTag: $QUT_USERNAME
  purposeTag: assessment 3
  region: $AWS_REGION
  appUrl: https://$dist_domain/
studentDetail:
  studentID: $STUDENT_ID
  studentFirstName: Yun Chi
  studentLastName: Yip
EOF
} > "$out"
log "Wrote $out ($(grep -c '  - type:' "$out") resources)"
